class Team {
  final int id;
  final String name;
  final String shortName;
  final String logoUrl;
  final String nationality;
  final int gpStarts;
  final int wins;
  final int podiums;
  final int poles;
  final int points;
  final int fastestLaps;
  final int driversChampionships;
  final int constructorsChampionships;


  Team({required this.id, required this.name, required this.shortName, required this.logoUrl, required this.nationality, required this.gpStarts, required this.wins, required this.podiums, required this.poles, required this.points, required this.fastestLaps, required this.driversChampionships, required this.constructorsChampionships});
}