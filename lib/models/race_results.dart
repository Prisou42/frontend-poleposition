class RaceResult {
  final int id;
  final int raceId;
  final int driverId;
  final int position;
  final int TeamId;
  final int gridPosition;
  final double points;
  final int lapsCompleted;
  final int fastestLap;
  final String status;
  RaceResult({required this.id, required this.raceId, required this.driverId, required this.position, required this.TeamId, required this.gridPosition, required this.points, required this.lapsCompleted, required this.fastestLap, required this.status});


}